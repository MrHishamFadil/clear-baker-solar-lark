/** Arabic letters only (no harakat) — used so we never rewrite an already-vocalized word. */
const LETTER = "\\u0621-\\u063A\\u0641-\\u064A\\u0671-\\u06D3";

function wordRe(from: string) {
  return new RegExp(`(?:(?<![${LETTER}])|(?<=[وف]))${from}(?![${LETTER}])`, "g");
}

