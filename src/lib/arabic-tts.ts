function applyLexicon(text: string) {
  const pairs = [...LEXICON].sort((a, b) => b[0].length - a[0].length);
  let out = text;
  for (const [from, to] of pairs) {
    out = out.replace(wordRe(from), to);
  }
  return out;
}

function applyTabbaq(text: string) {
  const stem = new RegExp(
    `(?<![${LETTER}])([أنيت])طبق(ها|هما|هم|هن|ه|ك|كم|كن|ت|وا)?(?![${LETTER}])`,
    "g",
  );
  const prefix: Record<string, string> = {
    أ: "أُطَبِّق",
    ن: "نُطَبِّق",
    ي: "يُطَبِّق",
    ت: "تُطَبِّق",
  };
  return text
    .replace(stem, (_, p: string, s: string) => prefix[p] + (s || ""))
    .replace(wordRe("طبقت"), "طَبَّقْت")
    .replace(wordRe("طبقوا"), "طَبَّقُوا")
    .replace(wordRe("طبقها"), "طَبِّقْها")
    .replace(wordRe("طبق"), "طَبِّق");
}

function normalizePunctuation(text: string) {
  return text
    .replace(/\u06D4/g, ".")
    .replace(/[?؟]+/g, "؟")
    .replace(/;/g, "؛")
    .replace(/,/g, "،")
    .replace(/\.{3}|…/g, "،")
    .replace(/[·•]/g, "،")
    .replace(/\s*[—–]\s*/g, "، ")
    .replace(/\s*\/\s*/g, "، ")
    .replace(/"/g, "")
    .replace(/\s*\[pause\]\s*/gi, "، ")
    .replace(/(?:،\s*){2,}/g, "، ")
    .replace(/\s{2,}/g, " ")
    .replace(/^[،\s]+|[،\s]+$/g, "")
    .replace(/([^\s])(؟|!|\.)/g, "$1$2")
    .trim();
}

/** Drop Latin asides that make the Arabic voice switch mid-sentence. */
function stripLatinAsides(text: string) {
  return text
    .replace(/\s*\((?:IB\s*)?PYP\s*\/\s*MYP\s*\/\s*DP\)/gi, "")
    .replace(/\bPYP\b|\bMYP\b|\bDP\b|\bIB\b/g, "")
    .replace(/\bJPIS\b/g, "مدارس جدة الخاصة العالمية")
    .replace(/\s*\([A-Za-z0-9][^)]*\)/g, "")
    .replace(/\s{2,}/g, " ")
    .trim();
}

/**
 * Prepare Arabic for neural TTS:
 * grammar-facing tashkeel, shadda on doubled letters, Arabic punctuation pauses.
 */
export function prepareArabicTts(text: string) {
  let out = text.replace(/ﷺ/g, " صلى الله عليه وسلَّم ");
  out = stripLatinAsides(out);
  out = applyTabbaq(out);
  out = applyLexicon(out);
  out = normalizePunctuation(out);
  return out.replace(/\s{2,}/g, " ").trim();
}
